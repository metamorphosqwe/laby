/*
 * Лабораторная работа №1
 * Среда программирования C++. Классы.
 * Предметная область: Студент (Student).
 *
 * Класс Student хранит три свойства:
 *   - course  - номер курса;
 *   - group   - номер группы;
 *   - grades  - статический массив оценок за сессию (SIZE элементов).
 *
 * Динамические массивы, указатели и контейнеры STL не используются.
 */

#include <iostream> // ввод-вывод: cout, endl
#include <cstdlib>  // system()
#include <clocale>  // setlocale()
using namespace std;

// Размер статического массива оценок.
// Вынесен в константу, чтобы не использовать "магическое число" 5 в коде.
const int SIZE = 5;

class Student
{
private:
    // Все данные класса закрыты (private): доступ к ним
    // возможен только через открытые методы TO_GET / TO_SET.
    int course;       // номер курса (1, 2, 3, ...)
    int group;        // номер группы
    int grades[SIZE]; // оценки за последнюю сессию

public:
    // ---------------------------------------------------------
    // КОНСТРУКТОРЫ
    // ---------------------------------------------------------

    // Конструктор по умолчанию.
    // Инициализирует поля значениями по умолчанию:
    // курс = 1, группа = 0, все оценки = 0.
    Student()
    {
        course = 1;
        group = 0;
        for (int i = 0; i < SIZE; i++)
        {
            grades[i] = 0;
        }
    }

    // Конструктор с параметрами.
    // c   - номер курса;
    // g   - номер группы;
    // arr - массив из SIZE оценок.
    // Массив копируется поэлементно в цикле, так как
    // присвоить один массив другому оператором "=" нельзя.
    Student(int c, int g, const int arr[])
    {
        course = c;
        group = g;
        for (int i = 0; i < SIZE; i++)
        {
            grades[i] = arr[i];
        }
    }

    // Конструктор копирования.
    // Создаёт новый объект как независимую копию объекта other.
    // Параметр передаётся по константной ссылке, чтобы избежать
    // бесконечной рекурсии и лишнего копирования.
    // Массив оценок копируется поэлементно, поэтому изменение
    // копии не влияет на исходный объект.
    Student(const Student &other)
    {
        course = other.course;
        group = other.group;
        for (int i = 0; i < SIZE; i++)
        {
            grades[i] = other.grades[i];
        }
    }

    // ---------------------------------------------------------
    // МЕТОД ВЫВОДА
    // ---------------------------------------------------------

    // TO_SHOW - выводит всю информацию об объекте в одну строку.
    // Метод помечен const: он не изменяет объект.
    void TO_SHOW() const
    {
        cout << "Курс: " << course;
        cout << " | Группа: " << group;
        cout << " | Оценки: ";
        for (int i = 0; i < SIZE; i++)
        {
            cout << grades[i] << " ";
        }
        cout << endl;
    }

    // ---------------------------------------------------------
    // МЕТОДЫ ПОЛУЧЕНИЯ ЗНАЧЕНИЙ (TO_GET)
    // ---------------------------------------------------------

    // Возвращает номер курса.
    int TO_GET_Course() const { return course; }

    // Возвращает номер группы.
    int TO_GET_Group() const { return group; }

    // Возвращает оценку с индексом i (нумерация с нуля).
    // Если индекс выходит за границы массива, возвращает -1,
    // чтобы не обращаться к чужой памяти.
    int TO_GET_Grade(int i) const
    {
        if (i < 0 || i >= SIZE)
            return -1;
        return grades[i];
    }

    // ---------------------------------------------------------
    // МЕТОДЫ УСТАНОВКИ ЗНАЧЕНИЙ (TO_SET)
    // ---------------------------------------------------------

    // Устанавливает номер курса.
    void TO_SET_Course(int c) { course = c; }

    // Устанавливает номер группы.
    void TO_SET_Group(int g) { group = g; }

    // Устанавливает оценку с индексом i.
    // При неверном индексе объект остаётся без изменений.
    void TO_SET_Grade(int i, int value)
    {
        if (i >= 0 && i < SIZE)
        {
            grades[i] = value;
        }
    }

    // ---------------------------------------------------------
    // ПЕРЕГРУЖЕННЫЕ ОПЕРАТОРЫ
    // ---------------------------------------------------------

    // Оператор присваивания "=".
    // Семантика: все поля левого объекта становятся равными полям
    // правого, включая поэлементное копирование массива оценок.
    // Проверка this != &other защищает от самоприсваивания (a = a).
    // Возвращается ссылка на текущий объект, что позволяет
    // записывать цепочки присваиваний: a = b = c.
    Student &operator=(const Student &other)
    {
        if (this != &other)
        {
            course = other.course;
            group = other.group;
            for (int i = 0; i < SIZE; i++)
            {
                grades[i] = other.grades[i];
            }
        }
        return *this;
    }

    // Бинарный оператор "+".
    // Семантика: "объединение" двух студентов.
    //   - оценки складываются поэлементно (суммарные баллы
    //     по каждому из SIZE предметов);
    //   - курс берётся наибольший из двух;
    //   - группа берётся от левого операнда.
    // Результат возвращается как НОВЫЙ объект по значению,
    // поэтому исходные операнды не изменяются (метод const).
    Student operator+(const Student &other) const
    {
        Student result;
        if (course > other.course)
        {
            result.course = course;
        }
        else
        {
            result.course = other.course;
        }
        result.group = group;
        for (int i = 0; i < SIZE; i++)
        {
            result.grades[i] = grades[i] + other.grades[i];
        }
        return result;
    }

    // Унарный префиксный оператор "++".
    // Семантика: перевод студента на следующий курс -
    // номер курса увеличивается на 1.
    // Возвращается ссылка на изменённый объект, чтобы результат
    // можно было использовать в выражениях.
    Student &operator++()
    {
        course++;
        return *this;
    }
};

int main()
{
    // Настройка кодировки консоли для вывода русского текста (Windows).
    system("chcp 65001");
    setlocale(LC_ALL, "ru_RU.UTF-8");

    // ----- 1. Создание трёх объектов тремя разными конструкторами -----
    cout << "=== Создание объектов ===" << endl;

    // Объект 1 - конструктор по умолчанию.
    Student s1;
    cout << "Объект 1 (по умолчанию): ";
    s1.TO_SHOW();

    // Объект 2 - конструктор с параметрами.
    int g[SIZE] = {8, 9, 7, 10, 9};
    Student s2(2, 29, g);
    cout << "Объект 2 (с параметрами): ";
    s2.TO_SHOW();

    // Объект 3 - конструктор копирования (копия объекта 2).
    Student s3(s2);
    cout << "Объект 3 (копия объекта 2): ";
    s3.TO_SHOW();

    // ----- 2. Демонстрация методов TO_SET -----
    cout << endl
         << "=== Методы TO_SET ===" << endl;

    // Меняем все свойства объекта 1.
    s1.TO_SET_Course(1);
    s1.TO_SET_Group(15);
    int newGrades[SIZE] = {6, 7, 5, 8, 6};
    for (int i = 0; i < SIZE; i++)
    {
        s1.TO_SET_Grade(i, newGrades[i]);
    }
    cout << "Объект 1 после TO_SET: ";
    s1.TO_SHOW();

    // Меняем одну оценку в объекте 3 и убеждаемся, что объект 2
    // не изменился: массив был скопирован, а не передан по ссылке.
    s3.TO_SET_Grade(4, 5);
    cout << "Объект 3 после TO_SET_Grade(4, 5): ";
    s3.TO_SHOW();
    cout << "Объект 2 (не изменился): ";
    s2.TO_SHOW();

    // ----- 3. Демонстрация методов TO_GET -----
    cout << endl
         << "=== Методы TO_GET ===" << endl;
    cout << "Курс объекта 2: " << s2.TO_GET_Course() << endl;
    cout << "Группа объекта 2: " << s2.TO_GET_Group() << endl;
    // Индекс 3 соответствует четвёртой оценке (нумерация с нуля).
    cout << "Оценка №4 объекта 2: ";
    cout << s2.TO_GET_Grade(3) << endl;

    // ----- 4. Оператор присваивания -----
    cout << endl
         << "=== Оператор = ===" << endl;
    s1 = s2;
    cout << "Объект 1 после s1 = s2: ";
    s1.TO_SHOW();

    // ----- 5. Бинарный оператор + -----
    cout << endl
         << "=== Бинарный оператор + ===" << endl;
    // Результат - новый объект; s2 и s3 остаются прежними.
    Student s4 = s2 + s3;
    cout << "Результат s2 + s3: ";
    s4.TO_SHOW();

    // ----- 6. Унарный оператор ++ -----
    cout << endl
         << "=== Унарный оператор ++ ===" << endl;
    cout << "Объект 3 до ++: ";
    s3.TO_SHOW();
    ++s3;
    cout << "Объект 3 после ++: ";
    s3.TO_SHOW();

    system("pause");
    return 0;
}
