/*
 * Лабораторная работа №2
 * Перегрузка функций. Разработка и реализация пользовательских классов.
 *
 * За основу взят класс Student из лабораторной работы №1
 * (поля: course, group, grades[SIZE]). В класс добавлены перегруженные
 * методы, иллюстрирующие разные виды перегрузки функций:
 *
 *   1. разное количество параметров   - TO_SET_Grade(int, int) и
 *                                       TO_SET_Grade(int);
 *   2. разные типы параметров         - TO_SET_Grade(int, int) и
 *                                       TO_SET_Grade(int, double);
 *   3. различие и по числу, и по типу - TO_SET_Grade(int, int) и
 *                                       TO_SET_Grade(double);
 *   4. const-квалификаторы            - TO_GET_Grade(int) const и
 *                                       TO_GET_Grade(int);
 *                                       TO_COMPARE(Student&) и
 *                                       TO_COMPARE(const Student&);
 *   5. перегрузка только по типу возвращаемого значения невозможна
 *      (пример приведён в комментарии внутри класса).
 *
 * Динамические массивы, указатели и контейнеры STL не используются.
 */

#include <iostream> // ввод-вывод: cout, endl
#include <cstdlib>  // system()
#include <clocale>  // setlocale()
using namespace std;

// Размер статического массива оценок.
const int SIZE = 5;

class Student
{
private:
    int course;       // номер курса
    int group;        // номер группы
    int grades[SIZE]; // оценки за последнюю сессию

    // Вспомогательный метод: округление вещественной оценки
    // до ближайшего целого (оценки неотрицательные).
    // static - метод не зависит от конкретного объекта.
    static int Round(double value)
    {
        return (int)(value + 0.5);
    }

public:
    // ---------------------------------------------------------
    // КОНСТРУКТОРЫ (из лабораторной работы №1)
    // ---------------------------------------------------------

    // Конструктор по умолчанию: курс = 1, группа = 0, оценки = 0.
    Student()
    {
        course = 1;
        group = 0;
        for (int i = 0; i < SIZE; i++)
        {
            grades[i] = 0;
        }
    }

    // Конструктор с параметрами: массив копируется поэлементно.
    Student(int c, int g, const int arr[])
    {
        course = c;
        group = g;
        for (int i = 0; i < SIZE; i++)
        {
            grades[i] = arr[i];
        }
    }

    // Конструктор копирования: независимая копия, включая массив.
    Student(const Student &other)
    {
        course = other.course;
        group = other.group;
        for (int i = 0; i < SIZE; i++)
        {
            grades[i] = other.grades[i];
        }
    }

    // Вывод всей информации об объекте. Метод const: объект
    // не изменяется, поэтому его можно вызывать и для const-объектов.
    void TO_SHOW() const
    {
        cout << "Курс: " << course;
        cout << " | Группа: " << group;
        cout << " | Оценки: ";
        for (int i = 0; i < SIZE; i++)
        {
            cout << grades[i] << " ";
        }
        cout << endl;
    }

    // ---------------------------------------------------------
    // ПРОСТЫЕ МЕТОДЫ ДОСТУПА
    // ---------------------------------------------------------

    int TO_GET_Course() const { return course; }
    int TO_GET_Group() const { return group; }
    void TO_SET_Course(int c) { course = c; }
    void TO_SET_Group(int g) { group = g; }

    // Сумма всех оценок (используется при сравнении студентов).
    int TO_GET_Sum() const
    {
        int sum = 0;
        for (int i = 0; i < SIZE; i++)
        {
            sum += grades[i];
        }
        return sum;
    }

    // ---------------------------------------------------------
    // 1. ПЕРЕГРУЗКА С РАЗНЫМ КОЛИЧЕСТВОМ ПАРАМЕТРОВ
    // ---------------------------------------------------------
    // Сигнатуры различаются числом параметров: (int, int) и (int).
    // Компилятор выбирает функцию по числу аргументов в вызове:
    //   s.TO_SET_Grade(0, 6)  - два аргумента, первая версия;
    //   s.TO_SET_Grade(5)     - один аргумент, вторая версия.

    // Устанавливает оценку с индексом i.
    void TO_SET_Grade(int i, int value)
    {
        if (i >= 0 && i < SIZE)
        {
            grades[i] = value;
        }
    }

    // Устанавливает одно и то же значение для ВСЕХ оценок.
    void TO_SET_Grade(int value)
    {
        for (int i = 0; i < SIZE; i++)
        {
            grades[i] = value;
        }
    }

    // ---------------------------------------------------------
    // 2. ПЕРЕГРУЗКА С РАЗНЫМИ ТИПАМИ ПАРАМЕТРОВ
    // ---------------------------------------------------------
    // Число параметров одинаково (2), но тип второго параметра
    // различается: (int, int) и (int, double).
    // Компилятор выбирает версию с точным совпадением типов:
    //   s.TO_SET_Grade(1, 7)    - второй аргумент int    -> (int, int);
    //   s.TO_SET_Grade(1, 7.6)  - второй аргумент double -> (int, double).
    // Версия с double округляет значение до ближайшего целого.
    void TO_SET_Grade(int i, double value)
    {
        if (i >= 0 && i < SIZE)
        {
            grades[i] = Round(value);
        }
    }

    // ---------------------------------------------------------
    // 3. РАЗЛИЧИЕ И ПО ЧИСЛУ, И ПО ТИПУ ПАРАМЕТРОВ
    // ---------------------------------------------------------
    // Сигнатура (double) отличается от (int, int) и числом
    // параметров (1 против 2), и типом первого параметра
    // (double против int); от (int) - типом параметра.
    //   s.TO_SET_Grade(9.4)  - один аргумент типа double.
    // Устанавливает округлённое значение для ВСЕХ оценок.
    void TO_SET_Grade(double value)
    {
        int rounded = Round(value);
        for (int i = 0; i < SIZE; i++)
        {
            grades[i] = rounded;
        }
    }

    // ---------------------------------------------------------
    // 4. ПЕРЕГРУЗКА С ИСПОЛЬЗОВАНИЕМ const
    // ---------------------------------------------------------

    // 4.1. const-квалификатор метода (относится к неявному
    // параметру this).
    //
    // const-версия: гарантирует, что объект не изменится. Только
    // она может вызываться для const-объектов. Возвращает копию
    // значения, поэтому изменить оценку через результат нельзя.
    // Для неверного индекса возвращает -1.
    int TO_GET_Grade(int i) const
    {
        if (i < 0 || i >= SIZE)
            return -1;
        return grades[i];
    }

    // не-const версия: вызывается для обычных (изменяемых) объектов.
    // Возвращает ССЫЛКУ на оценку, поэтому её можно изменить прямо
    // через результат вызова: s.TO_GET_Grade(1) = 10;
    // Для неверного индекса возвращается ссылка на статическую
    // «заглушку», чтобы не выйти за границы массива.
    //
    // Как компилятор различает версии: если объект const - доступна
    // только const-версия; если объект не const - предпочтительна
    // не-const версия (она точнее соответствует типу this).
    int &TO_GET_Grade(int i)
    {
        static int stub = 0;
        if (i < 0 || i >= SIZE)
        {
            stub = 0;
            return stub;
        }
        return grades[i];
    }

    // 4.2. const-квалификатор параметра-ссылки.
    // Сигнатуры (Student&) и (const Student&) - РАЗНЫЕ функции.
    // Сравнивает суммы оценок: 1 - у текущего студента сумма больше,
    // -1 - меньше, 0 - равны. Выводит, какая версия вызвана.
    //
    // Версия для изменяемого объекта: выбирается, когда аргумент -
    // обычный (не const) объект.
    int TO_COMPARE(Student &other) const
    {
        cout << "[TO_COMPARE(Student&)]";
        if (TO_GET_Sum() > other.TO_GET_Sum())
            return 1;
        if (TO_GET_Sum() < other.TO_GET_Sum())
            return -1;
        return 0;
    }

    // Версия для const-объекта: выбирается, когда аргумент - const-объект
    // или временный объект (временный объект нельзя привязать к
    // неконстантной ссылке Student&).
    int TO_COMPARE(const Student &other) const
    {
        cout << "[TO_COMPARE(const Student&)]";
        if (TO_GET_Sum() > other.TO_GET_Sum())
            return 1;
        if (TO_GET_Sum() < other.TO_GET_Sum())
            return -1;
        return 0;
    }

    // Примечание: const при передаче ПО ЗНАЧЕНИЮ перегрузкой не
    // является. Функции f(int x) и f(const int x) имеют одну и ту же
    // сигнатуру (копия параметра всё равно локальна), и их одновременное
    // объявление - ошибка «redefinition».

    // ---------------------------------------------------------
    // 5. ПЕРЕГРУЗКА ТОЛЬКО ПО ВОЗВРАЩАЕМОМУ ТИПУ - НЕВОЗМОЖНА
    // ---------------------------------------------------------
    // Следующий код НЕ СКОМПИЛИРУЕТСЯ, поэтому закомментирован:
    //
    //     int    TO_GET_Course() const { return course; }
    //     double TO_GET_Course() const { return course; }   // ОШИБКА
    //
    // Компилятор выбирает функцию по имени и списку аргументов при
    // вызове. Выражение s.TO_GET_Course() одинаково для обеих версий,
    // тип результата при выборе не учитывается (результат может
    // быть вообще не использован), поэтому выбор неоднозначен.
    // Компилятор сообщает об ошибке уже при объявлении второй функции
    // (g++: «cannot be overloaded with»).
};

int main()
{
    // Настройка кодировки консоли (Windows).
    system("chcp 65001");
    setlocale(LC_ALL, "ru_RU.UTF-8");

    int g[SIZE] = {8, 9, 7, 10, 9};
    Student s(2, 29, g);
    cout << "=== Исходный объект ===" << endl;
    s.TO_SHOW();

    // ----- 1. Разное количество параметров -----
    cout << endl;
    cout << "=== 1. Разное количество параметров ===" << endl;

    // Два аргумента -> вызывается TO_SET_Grade(int, int).
    s.TO_SET_Grade(0, 6);
    cout << "TO_SET_Grade(0, 6):   ";
    s.TO_SHOW();

    // Один аргумент типа int -> вызывается TO_SET_Grade(int).
    s.TO_SET_Grade(5);
    cout << "TO_SET_Grade(5):      ";
    s.TO_SHOW();

    // ----- 2. Разные типы параметров -----
    cout << endl
         << "=== 2. Разные типы параметров ===" << endl;

    // Второй аргумент int -> TO_SET_Grade(int, int).
    s.TO_SET_Grade(1, 7);
    cout << "TO_SET_Grade(1, 7):   ";
    s.TO_SHOW();

    // Второй аргумент double -> TO_SET_Grade(int, double),
    // значение 7.6 округляется до 8.
    s.TO_SET_Grade(2, 7.6);
    cout << "TO_SET_Grade(2, 7.6): ";
    s.TO_SHOW();

    // ----- 3. Различие и по числу, и по типу параметров -----
    cout << endl
         << "=== 3. Число и тип параметров ===" << endl;

    // Один аргумент типа double -> TO_SET_Grade(double),
    // значение 9.4 округляется до 9 и записывается во все оценки.
    s.TO_SET_Grade(9.4);
    cout << "TO_SET_Grade(9.4):    ";
    s.TO_SHOW();

    // ----- 4. Перегрузка с const -----
    cout << endl
         << "=== 4. Перегрузка с const ===" << endl;

    // 4.1. const-квалификатор метода.
    int h[SIZE] = {6, 7, 8, 9, 10};
    const Student cs(3, 15, h); // константный объект
    Student s2(2, 29, g);       // обычный объект

    // Для const-объекта вызывается const-версия TO_GET_Grade(int) const.
    cout << "const-объект, оценка №2: ";
    cout << cs.TO_GET_Grade(1) << endl;
    // cs.TO_GET_Grade(1) = 5;  // ОШИБКА: const-версия возвращает копию

    // Для обычного объекта вызывается не-const версия, возвращающая
    // ссылку: оценку можно изменить через результат вызова.
    s2.TO_GET_Grade(1) = 10;
    cout << "s2 после TO_GET_Grade(1) = 10: ";
    s2.TO_SHOW();

    // 4.2. const-квалификатор параметра-ссылки.
    int r;

    // Аргумент - обычный объект -> TO_COMPARE(Student&).
    r = s2.TO_COMPARE(s);
    cout << " результат: " << r << endl;

    // Аргумент - const-объект -> TO_COMPARE(const Student&).
    r = s2.TO_COMPARE(cs);
    cout << " результат: " << r << endl;

    // Аргумент - временный объект -> TO_COMPARE(const Student&),
    // так как временный объект нельзя привязать к Student&.
    r = s2.TO_COMPARE(Student(1, 1, g));
    cout << " результат: " << r << endl;

    // ----- 5. Перегрузка только по возвращаемому типу -----
    // Невозможна: пример в закомментированном виде приведён
    // в конце определения класса.
    system("pause");
    return 0;
}
