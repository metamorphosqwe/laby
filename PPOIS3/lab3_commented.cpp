// Лабораторная работа №3
// Тема: «Ссылочный тип. Инициализация классов, конструкторы
//        и деструкторы»
// Предметная область: «Студент». Вариант: динамический int[].
// ============================================================

#include <iostream>   // cout, endl
#include <cstdlib>    // system()
#include <clocale>    // setlocale()
using namespace std;

// Размер массива оценок. Это константа времени компиляции, поэтому
// её можно использовать в типе «ссылка на массив» int (&)[SIZE].
const int SIZE = 5;

class Student {
private:
    int course;          // курс
    int group;           // группа

    // Указатель на динамический массив оценок. Сам массив лежит
    // в куче: создаётся через new[] в конструкторах,
    // удаляется через delete[] в деструкторе.
    int* grades;

    // ССЫЛОЧНОЕ ПОЛЕ: псевдоним внешней переменной (рейтинг).
    // Правила ссылок в C++:
    //  1) должна быть инициализирована при создании объекта,
    //     то есть ТОЛЬКО в списке инициализации конструктора;
    //  2) после этого её нельзя перепривязать к другой переменной;
    //  3) всё, что делается с rating, делается с внешней переменной.
    int& rating;

    // Статический счётчик живых объектов (один на весь класс).
    // +1 в конструкторах, -1 в деструкторе. Если в конце он равен 0,
    // значит каждый созданный объект был уничтожен (нет утечек).
    static int alive;

    // Переменная для конструктора по умолчанию: ссылка не бывает
    // «пустой», поэтому ей нужно к чему-то привязаться.
    static int defaultRating;

public:
    // ---------- Конструктор по умолчанию ----------
    // После двоеточия — список инициализации: здесь привязывается ссылка.
    Student() : rating(defaultRating) {
        course = 1;
        group = 0;
        grades = new int[SIZE];            // выделяем память в куче
        for (int i = 0; i < SIZE; i++) {
            grades[i] = 0;                 // new[] не обнуляет память сам
        }
        alive++;
        cout << "  [Конструктор по умолчанию] объектов: "
            << alive << endl;
    }

    // ---------- Конструктор с параметрами ----------
    // arr — исходные оценки (копируем значения, а не указатель!).
    // r — внешняя переменная, передаётся ПО ССЫЛКЕ (int&), иначе
    // поле rating привязалось бы к временной копии параметра,
    // которая исчезнет при выходе из конструктора.
    Student(int c, int g, const int arr[], int& r) : rating(r) {
        course = c;
        group = g;
        grades = new int[SIZE];
        for (int i = 0; i < SIZE; i++) {
            grades[i] = arr[i];
        }
        alive++;
        cout << "  [Конструктор с параметрами] объектов: "
            << alive << endl;
    }

    // ---------- Конструктор копирования ----------
    // Вызывается при Student b(a); при передаче объекта в функцию
    // по значению; при возврате по значению (если нет оптимизации).
    // Без него компилятор скопировал бы указатель grades:
    // два объекта указывали бы на ОДИН массив (поверхностное
    // копирование), а деструктор освободил бы его дважды.
    // Здесь выделяется НОВЫЙ массив и копируются значения
    // (глубокое копирование).
    // Ссылка привязывается к той же переменной, что и у other.
    Student(const Student& other) : rating(other.rating) {
        course = other.course;
        group = other.group;
        grades = new int[SIZE];
        for (int i = 0; i < SIZE; i++) {
            grades[i] = other.grades[i];
        }
        alive++;
        cout << "  [Конструктор копирования] объектов: "
            << alive << endl;
    }

    // ---------- Деструктор ----------
    // Вызывается автоматически при выходе объекта из области видимости.
    // Массив, созданный через new[], удаляется через delete[]
    // (delete без [] для массивов — ошибка).
    ~Student() {
        delete[] grades;
        alive--;
        cout << "  [Деструктор] объектов: " << alive << endl;
    }

    // ---------- Оператор присваивания ----------
    // Вызывается при s1 = s2, когда оба объекта уже существуют.
    // Вместе с деструктором и конструктором копирования образует
    // «правило трёх»: определили одно — определяйте все три.
    Student& operator=(const Student& other) {
        // Защита от самоприсваивания (s = s): иначе мы удалили бы
        // массив, из которого собираемся копировать.
        if (this != &other) {
            delete[] grades;               // освобождаем старый массив
            course = other.course;
            group = other.group;
            grades = new int[SIZE];        // выделяем новый
            for (int i = 0; i < SIZE; i++) {
                grades[i] = other.grades[i];
            }
            // rating НЕ присваиваем: ссылку нельзя перепривязать, а
            // запись rating = other.rating изменила бы значение
            // внешней переменной, а не саму привязку.
        }
        cout << "  [Оператор =]" << endl;
        return *this;                      // позволяет писать a = b = c
    }

    // Вывод объекта на экран (const: объект не изменяется).
    void TO_SHOW() const {
        cout << "Курс: " << course;
        cout << " | Группа: " << group;
        cout << " | Оценки: ";
        for (int i = 0; i < SIZE; i++) {
            cout << grades[i] << " ";
        }
        cout << "| Рейтинг: " << rating << endl;
    }

    // Простые методы доступа (возврат по значению — возвращается копия).
    int TO_GET_Course() const { return course; }
    int TO_GET_Group() const { return group; }

    // Сумма оценок.
    int TO_GET_Sum() const {
        int sum = 0;
        for (int i = 0; i < SIZE; i++) {
            sum += grades[i];
        }
        return sum;
    }

    // Чтение рейтинга через ссылку.
    int TO_GET_Rating() const { return rating; }

    // Запись через ссылку: меняется ВНЕШНЯЯ переменная, к которой
    // привязано поле rating, и это видят все, кто с ней связан.
    void TO_SET_Rating(int r) { rating = r; }

    // ==========================================================
    // Три способа возврата массива из метода
    // ==========================================================

    // Способ 1. Возврат УКАЗАТЕЛЯ на массив.
    // Можно читать и менять элементы, но размер теряется:
    // sizeof(указатель) — это размер самого указателя, а не массива.
    int* TO_GET_Array() { return grades; }

    // Способ 2. Возврат ССЫЛКИ на массив.
    // Тип int (&)[SIZE] хранит размер: работают sizeof и range-for.
    // Скобки обязательны: int& f()[N] означало бы другое.
    // Так как массив динамический (int*), для получения ссылки на
    // массив из SIZE элементов нужно приведение reinterpret_cast.
    int (&TO_GET_ArrayRef())[SIZE] {
        return reinterpret_cast<int(&)[SIZE]>(*grades);
    }

    // Способ 3. Возврат ССЫЛКИ на отдельный элемент.
    // Результат вызова можно использовать слева от =, ++ и т.д.:
    // s.TO_GET_Element(0) = 5;
    int& TO_GET_Element(int i) {
        // При неверном индексе нельзя вернуть ссылку на несуществующий
        // элемент, поэтому возвращаем ссылку на запасную переменную
        // (static живёт всё время работы программы).
        static int stub = 0;
        if (i < 0 || i >= SIZE) {
            stub = 0;
            return stub;
        }
        return grades[i];
    }

    // Статический метод: вызывается без объекта, Student::TO_GET_Alive().
    static int TO_GET_Alive() { return alive; }
};

// Определение статических полей вне класса (обязательно, один раз).
int Student::alive = 0;
int Student::defaultRating = 0;

// ==============================================================
// Внешние функции: передача и возврат по значению и по ссылке
// ==============================================================

// ПЕРЕДАЧА ПО ЗНАЧЕНИЮ: параметр s — КОПИЯ (вызывается конструктор
// копирования). Изменения затрагивают только копию, при выходе из
// функции вызывается деструктор копии. Оригинал остаётся прежним.
void changeByValue(Student s) {
    s.TO_GET_Element(0) = 1;
    cout << "  внутри функции (копия): ";
    s.TO_SHOW();
}

// ПЕРЕДАЧА ПО ССЫЛКЕ: s — другое имя того же объекта. Копия не
// создаётся (быстрее), изменения видны в оригинале.
void changeByRef(Student& s) {
    s.TO_GET_Element(0) = 1;
    cout << "  внутри функции (оригинал): ";
    s.TO_SHOW();
}

// ВОЗВРАТ ПО ССЫЛКЕ: возвращается сам объект (a или b), а не копия.
// Запись через результат изменит оригинал. Нельзя возвращать ссылку
// на локальную переменную: она исчезнет при выходе из функции.
Student& bestByRef(Student& a, Student& b) {
    return (a.TO_GET_Sum() >= b.TO_GET_Sum()) ? a : b;
}

// ВОЗВРАТ ПО ЗНАЧЕНИЮ: создаётся копия (конструктор копирования),
// изменения копии оригинал не затрагивают.
Student bestByValue(Student& a, Student& b) {
    return (a.TO_GET_Sum() >= b.TO_GET_Sum()) ? a : b;
}

int main() {
    system("chcp 65001");                  // UTF-8 в консоли Windows
    setlocale(LC_ALL, "ru_RU.UTF-8");

    int g[SIZE] = {8, 9, 7, 10, 9};        // исходные оценки
    int groupRating = 70;                  // внешняя переменная для ссылки

    // ----- 1. Динамический массив -----
    cout << "=== 1. Динамический массив ===" << endl;
    {   // Отдельный блок: в конце его объекты уничтожаются, и мы
        // видим вызовы деструкторов.
        Student s1;                        // по умолчанию
        Student s2(2, 29, g, groupRating); // с параметрами
        Student s3(s2);                    // копирования
        cout << "s1: "; s1.TO_SHOW();
        cout << "s2: "; s2.TO_SHOW();
        cout << "s3: "; s3.TO_SHOW();

        // Меняем копию: s2 не должен измениться (глубокое копирование).
        cout << endl << "Изменяем оценку №1 у s3 (копия):" << endl;
        s3.TO_GET_Element(0) = 4;
        cout << "s2: "; s2.TO_SHOW();
        cout << "s3: "; s3.TO_SHOW();

        // Оператор присваивания: s1 уже существует.
        cout << endl << "Присваивание s1 = s2:" << endl;
        s1 = s2;
        cout << "s1: "; s1.TO_SHOW();
        s1.TO_GET_Element(4) = 5;
        cout << "s1 после изменения: "; s1.TO_SHOW();
        cout << "s2 не изменился:    "; s2.TO_SHOW();

        // Самоприсваивание не должно ничего сломать.
        cout << endl << "Самоприсваивание s1 = s1:" << endl;
        s1 = s1;
        cout << "s1: "; s1.TO_SHOW();
        cout << endl << "Выход из блока (освобождение памяти):"
            << endl;
    }   // здесь вызываются деструкторы s3, s2, s1 (в обратном порядке)
    cout << "Живых объектов: " << Student::TO_GET_Alive() << endl;

    // ----- 2. Ссылочная переменная -----
    cout << endl << "=== 2. Ссылочная переменная ===" << endl;
    Student a(2, 29, g, groupRating);
    Student b(a);                          // тоже привязан к groupRating
    cout << "groupRating = " << groupRating << endl;
    cout << "a: "; a.TO_SHOW();

    // Меняем переменную напрямую: объекты видят новое значение.
    groupRating = 85;
    cout << "groupRating = 85" << endl;
    cout << "a: "; a.TO_SHOW();
    cout << "b: "; b.TO_SHOW();

    // Меняем через объект: меняется сама переменная.
    a.TO_SET_Rating(90);
    cout << "a.TO_SET_Rating(90), groupRating = "
        << groupRating << endl;
    cout << "b: "; b.TO_SHOW();

    // Присваивание не перепривязывает ссылку.
    int otherRating = 50;
    int c[SIZE] = {5, 5, 5, 5, 5};
    Student d(1, 15, c, otherRating);
    cout << endl
        << "Присваивание a = d (ссылка не перепривязывается):"
        << endl;
    a = d;
    cout << "a: "; a.TO_SHOW();
    cout << "groupRating = " << groupRating
        << ", otherRating = " << otherRating << endl;

    // ----- 3. Передача и возврат -----
    cout << endl << "=== 3. Передача и возврат ===" << endl;
    cout << "Передача по значению:" << endl;
    changeByValue(b);                      // создаётся и удаляется копия
    cout << "  после вызова: ";
    b.TO_SHOW();                           // b не изменился
    cout << "Передача по ссылке:" << endl;
    changeByRef(b);
    cout << "  после вызова: ";
    b.TO_SHOW();                           // b изменился

    cout << endl << "Возврат по ссылке:" << endl;
    Student& best = bestByRef(a, b);       // best — псевдоним a или b
    best.TO_GET_Element(1) = 10;           // меняем оригинал
    cout << "a: "; a.TO_SHOW();
    cout << "b: "; b.TO_SHOW();
    cout << "Возврат по значению:" << endl;
    Student copy = bestByValue(a, b);      // независимая копия
    copy.TO_GET_Element(1) = 0;
    cout << "copy: "; copy.TO_SHOW();
    cout << "b:    "; b.TO_SHOW();         // b не изменился

    // ----- 4. Способы возврата массива -----
    cout << endl << "=== 4. Способы возврата массива ==="
        << endl;

    // Способ 1: указатель.
    int* p = b.TO_GET_Array();
    p[2] = 6;
    cout << "1) указатель, p[2] = 6: ";
    b.TO_SHOW();
    cout << "   sizeof(p) = " << sizeof(p) << endl;  // размер указателя

    // Способ 2: ссылка на массив.
    int (&r)[SIZE] = b.TO_GET_ArrayRef();
    cout << "2) ссылка на массив: ";
    for (int x : r) cout << x << " ";      // range-for работает
    cout << endl;
    r[3] = 7;
    cout << "   после r[3] = 7: ";
    b.TO_SHOW();
    cout << "   sizeof(r) = " << sizeof(r)  // 5 * sizeof(int)
        << " (" << SIZE << " элементов)" << endl;

    // Способ 3: ссылка на элемент.
    int& e = b.TO_GET_Element(4);
    e = 9;
    cout << "3) ссылка на элемент, e = 9: ";
    b.TO_SHOW();
    b.TO_GET_Element(0)++;                 // ++ прямо по результату вызова
    cout << "   TO_GET_Element(0)++: ";
    b.TO_SHOW();

    cout << endl << "Выход из main (освобождение памяти):" << endl;
    return 0;
}   // деструкторы copy, d, b, a
